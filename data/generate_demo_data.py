def _write(name: str, rows: list[dict]) -> Path:
    path = DATA_DIR / name
    if not rows:
        path.write_text("", encoding="utf-8")
        return path
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return path


def generate() -> None:
    _write("incidents.csv", INCIDENTS)
    _write("resources.csv", RESOURCES)
    _write("hospitals.csv", HOSPITALS)
    _write("shelters.csv", SHELTERS)
    _write("roads.csv", ROADS)
    print("Wrote simulated demo CSVs to", DATA_DIR)


if __name__ == "__main__":
    generate()
